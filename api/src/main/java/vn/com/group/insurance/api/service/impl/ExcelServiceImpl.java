    @Override
    public List<Map<String, String>> readNormalExcelWithHeader(MultipartFile file) throws IOException {
        List<Map<String, String>> dataList = new ArrayList<>();

        try (InputStream inputStream = file.getInputStream();
             Workbook workbook = WorkbookFactory.create(inputStream)) {

                // Assuming data is on the first sheet
                Sheet sheet = workbook.getSheetAt(0);

                // Evaluator and Formatter to handle numbers, dates, and formulas safely
                FormulaEvaluator evaluator = workbook.getCreationHelper().createFormulaEvaluator();
                DataFormatter formatter = new DataFormatter();

                // 1. Get the Header Row (Index 0)
                Row headerRow = sheet.getRow(0);
                if (headerRow == null) {
                    return dataList; // File is completely empty
                }

                // 2. Map the Headers
                List<String> headers = new ArrayList<>();
                int lastColNum = headerRow.getLastCellNum(); // Gets the actual number of columns

                for (int col = 0; col < lastColNum; col++) {
                    Cell cell = headerRow.getCell(col, Row.MissingCellPolicy.CREATE_NULL_AS_BLANK);
                    String headerName = formatter.formatCellValue(cell, evaluator).trim();

                    // Assign a fallback name if the header cell is blank
                    if (headerName.isEmpty()) {
                        headerName = "Column_" + col;
                    }
                    headers.add(headerName);
                }

                // 3. Read Data Rows (Starts from Index 1)
                int lastRowNum = sheet.getLastRowNum();

                for (int r = 1; r <= lastRowNum; r++) {
                    Row row = sheet.getRow(r);
                    if (row == null) continue;

                    Map<String, String> rowData = new LinkedHashMap<>();
                    boolean isRowCompletelyEmpty = true;

                    // Iterate strictly based on the number of headers found
                    for (int col = 0; col < headers.size(); col++) {
                        Cell cell = row.getCell(col, Row.MissingCellPolicy.CREATE_NULL_AS_BLANK);
                        String cellValue = formatter.formatCellValue(cell, evaluator).trim();

                        if (!cellValue.isEmpty()) {
                            isRowCompletelyEmpty = false;
                        }

                        rowData.put(headers.get(col), cellValue);
                    }

                    // Only add the row if it contains at least one non-empty value
                    if (!isRowCompletelyEmpty) {
                        dataList.add(rowData);
                    }
                }
        }

        return dataList;
    }

    @Override
    public List<Map<String, String>> readDynamicExcel(MultipartFile file) throws Exception {
        List<Map<String, String>> excelData = new ArrayList<>();

        try (InputStream inputStream = file.getInputStream();
             Workbook workbook = WorkbookFactory.create(inputStream)) {

                Sheet sheet = workbook.getSheetAt(0);

                // 1. Initialize Formula Evaluator
                FormulaEvaluator evaluator = workbook.getCreationHelper().createFormulaEvaluator();

                Row headerRow = sheet.getRow(0);
                if (headerRow == null) throw new IllegalArgumentException("Excel file is empty");

                List<String> headers = new ArrayList<>();
                for (Cell cell : headerRow) {
                    // Pass evaluator to header just in case headers are generated by formulas
                    headers.add(getCellValueAsString(cell, evaluator));
                }

                int lastRowNum = sheet.getLastRowNum();
                for (int i = 1; i <= lastRowNum; i++) {
                    Row row = sheet.getRow(i);
                    if (row == null) continue;

                    Map<String, String> rowData = new LinkedHashMap<>();
                    for (int colIndex = 0; colIndex < headers.size(); colIndex++) {
                        Cell cell = row.getCell(colIndex, Row.MissingCellPolicy.CREATE_NULL_AS_BLANK);

                        // 2. Pass evaluator to dynamically calculate formula results
                        rowData.put(headers.get(colIndex), getCellValueAsString(cell, evaluator));
                    }
                    excelData.add(rowData);
                }
        }
        return excelData;
    }

